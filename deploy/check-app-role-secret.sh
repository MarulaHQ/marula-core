#!/bin/sh
# The app-role credential, asserted without a cluster (F65).
#
# Why a script: the defect this lane closed was invisible to every other
# check. The Helm bootstrap Job set the role's password from the Secret on
# pre-install only, so a rotated Secret never reached the role, and the
# compose file required MARULA_APP_PASSWORD while being unable to apply it —
# the stack fell back to the literal migration 0114 mints. Both facts live in
# a rendered manifest, so both can be asserted from one, no cluster needed.
#
# Asserts:
#   1. the Helm bootstrap Job is a pre-install AND pre-upgrade hook;
#   2. it takes the password from the Secret (secretKeyRef), and the chosen
#      value never appears in the Job — nor anywhere in a staging render,
#      which takes every credential from an existing Secret;
#   3. the chart's own Secret carries the value when the chart mints it;
#   4. compose applies the password in a one-shot that runs after migrations
#      as the owner, and core-api waits for it;
#   5. PgBouncer's auth file is generated by a one-shot the pooler waits for,
#      and no userlist is checked in.
#
# Run it:      deploy/check-app-role-secret.sh
# Requires:    helm and docker compose (each leg is skipped with a warning
#              when the tool is absent). Does not start a container.
set -eu

ROOT=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
CHART="$ROOT/deploy/helm/marula"
FAIL=0

ok()   { printf '  ok   %s\n' "$*"; }
bad()  { FAIL=$((FAIL + 1)); printf '  FAIL %s\n' "$*"; }
skip() { printf '  skip %s\n' "$*"; }
head() { printf '\n== %s\n' "$*"; }
have() { command -v "$1" >/dev/null 2>&1; }

# The value a rotation would use. It is distinctive on purpose: finding it in
# a Job's args is the defect, and finding it nowhere in a staging render is
# the property.
SENTINEL='f65-not-a-real-app-password'

[ -f "$CHART/Chart.yaml" ] || { echo "missing deploy/helm/marula/Chart.yaml" >&2; exit 2; }

# ---------------------------------------------------------------------------
head "Helm bootstrap job"

if have helm; then
	RENDER=$(mktemp)
	trap 'rm -f "$RENDER"' EXIT

	# The staging profile: every credential comes from an existing Secret, so
	# nothing this render produces may carry a password at all.
	if helm template marula-staging "$CHART" \
		-f "$CHART/values-staging-pentest.yaml" \
		--set digestPinningEnforced=false \
		--set nonMarulaDigestPinningEnforced=false \
		> "$RENDER" 2>&1; then
		ok "staging profile renders"
	else
		bad "staging profile failed to render: $(tail -2 "$RENDER")"
	fi

	python3 - "$RENDER" "$SENTINEL" <<'PY' || FAIL=$((FAIL + 1))
import sys, pathlib

render = pathlib.Path(sys.argv[1]).read_text()
sentinel = sys.argv[2]
docs = [d for d in render.split("\n---\n") if d.strip()]

def doc_of(kind, name_fragment):
    for d in docs:
        if f"kind: {kind}" in d and name_fragment in d:
            return d
    return None

problems = []
job = doc_of("Job", "-pg-bootstrap")
if job is None:
    problems.append("no pg-bootstrap Job in the render")
else:
    hook = [l.strip() for l in job.splitlines() if "helm.sh/hook:" in l]
    if not hook:
        problems.append("the bootstrap Job has no helm.sh/hook annotation")
    else:
        value = hook[0].split("helm.sh/hook:", 1)[1].strip()
        for want in ("pre-install", "pre-upgrade"):
            if want not in value:
                problems.append(f"the hook annotation lacks {want}: {value}")
        if "pre-upgrade" in value:
            print("  ok   bootstrap Job is a pre-install,pre-upgrade hook")
    if "key: POSTGRES_APP_PASSWORD" not in job:
        problems.append("the Job does not read POSTGRES_APP_PASSWORD from the Secret")
    elif "secretKeyRef" not in job:
        problems.append("POSTGRES_APP_PASSWORD is not a secretKeyRef")
    else:
        print("  ok   the password comes from a secretKeyRef, not a literal")
    if sentinel in job:
        problems.append("the Job embeds the password literal")
    if "ALTER ROLE" not in job or "PASSWORD" not in job:
        problems.append("the Job no longer sets the role password")
    else:
        print("  ok   the Job still runs the ALTER ROLE")

# A staging render has no chart Secret at all: the sentinel must be absent
# from the whole thing.
if "kind: Secret" in render:
    problems.append("the staging profile rendered a Secret; it takes existingSecret")
elif sentinel in render:
    problems.append("the sentinel appears in a render that should carry no credential")
else:
    print("  ok   no password in the staging render (existingSecret)")

if problems:
    for p in problems:
        print(f"  FAIL {p}")
    sys.exit(1)
PY

	# And the chart-minted Secret path: the value belongs in the Secret and
	# nowhere else in the manifest.
	if helm template marula "$CHART" \
		--set digestPinningEnforced=false \
		--set nonMarulaDigestPinningEnforced=false \
		--set postgresql.appPassword="$SENTINEL" \
		--set postgresql.ownerPassword="$SENTINEL-owner" \
		> "$RENDER" 2>&1; then
		python3 - "$RENDER" "$SENTINEL" <<'PY' || FAIL=$((FAIL + 1))
import sys, pathlib

render = pathlib.Path(sys.argv[1]).read_text()
sentinel = sys.argv[2]
docs = [d for d in render.split("\n---\n") if d.strip()]
secret = [d for d in docs if "kind: Secret" in d and "POSTGRES_APP_PASSWORD" in d]
others = [d for d in docs if d not in secret and sentinel in d]

if not secret:
    print("  FAIL the chart Secret does not carry POSTGRES_APP_PASSWORD")
    sys.exit(1)
if others:
    kinds = ", ".join(sorted({l.split("kind:", 1)[1].strip() for d in others
                              for l in d.splitlines() if l.startswith("kind:")}))
    print(f"  FAIL the password leaked into: {kinds}")
    sys.exit(1)
print("  ok   the chart-minted Secret is the only document holding the value")
PY
	else
		bad "default-values render failed"
	fi
else
	skip "helm not available"
fi

# ---------------------------------------------------------------------------
head "Compose one-shots"

if have docker && have python3; then
	ENVDEV=$(mktemp)
	OUT=$(mktemp)
	trap 'rm -f "$ENVDEV" "$OUT"' EXIT
	cat >"$ENVDEV" <<'EOF'
JWT_SECRET=0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef
MARULA_SECRET_KEY=fedcba9876543210fedcba9876543210fedcba9876543210fedcba9876543210
MARULA_INTERNAL_TOKEN=check-internal-token
EMAIL_INTERNAL_TOKEN=check-email-internal-token
POSTGRES_PASSWORD=check-owner-password
MARULA_APP_PASSWORD=check-app-password
GARAGE_RPC_SECRET=0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef
GLITCHTIP_SECRET_KEY=check-glitchtip-secret
EOF
	if (cd "$ROOT" && docker compose --env-file "$ENVDEV" \
		-f deploy/docker-compose.yml config --format json > "$OUT" 2>/dev/null); then
		ok "compose renders"
	else
		bad "compose did not render"
	fi

	python3 - "$OUT" <<'PY' || FAIL=$((FAIL + 1))
import json, sys

services = json.load(open(sys.argv[1])).get("services", {})
problems = []

def depends(svc, dep, want):
    d = (services.get(svc) or {}).get("depends_on") or {}
    got = (d.get(dep) or {}).get("condition") if isinstance(d.get(dep), dict) else d.get(dep)
    return got == want

app = services.get("app-role-password")
if app is None:
    problems.append("no app-role-password one-shot")
else:
    env = app.get("environment") or {}
    cmd = json.dumps(app.get("command") or app.get("entrypoint") or "")
    if not depends("app-role-password", "migrate", "service_completed_successfully"):
        problems.append("the one-shot does not wait for migrations (the role does not exist before 0114)")
    elif not depends("app-role-password", "postgres", "service_healthy"):
        problems.append("the one-shot does not wait for postgres")
    elif "ALTER ROLE" not in cmd or ":'pw'" not in cmd:
        problems.append("the one-shot does not set the role password from the environment")
    elif env.get("MARULA_APP_PASSWORD") != "check-app-password":
        problems.append("the one-shot does not read MARULA_APP_PASSWORD")
    elif env.get("PGPASSWORD") != "check-owner-password":
        problems.append("the one-shot does not connect as the owner")
    else:
        print("  ok   app-role-password: owner connection, after migrate, ALTER from the env")

if not depends("core-api", "app-role-password", "service_completed_successfully"):
    problems.append("core-api does not wait for the one-shot")
else:
    print("  ok   core-api waits for it")

if "pooler-auth" not in services:
    problems.append("no pooler-auth one-shot; the pooler would have no auth file")
elif not depends("pgbouncer", "pooler-auth", "service_completed_successfully"):
    problems.append("pgbouncer does not wait for pooler-auth")
else:
    print("  ok   pooler-auth renders the auth file before the pooler starts")

if problems:
    for p in problems:
        print(f"  FAIL {p}")
    sys.exit(1)
PY

	if [ -e "$ROOT/deploy/pooler/userlist.txt" ]; then
		bad "deploy/pooler/userlist.txt is checked in again"
	else
		ok "no userlist.txt in the tree (the credential is generated, not shipped)"
	fi
	# Excludes this file: the pattern below is necessarily a literal in it.
	if grep -rq --exclude=check-app-role-secret.sh '"marula_app" "marula_app"' "$ROOT/deploy"; then
		bad "a file under deploy/ still holds the published app-role password"
	else
		ok "no file under deploy/ holds the literal marula_app password"
	fi
	# The same credential inside a URL is the shape that survived the first
	# check: `postgres://marula_app:marula_app@…` in a generated profile is
	# the literal, not a pair of YAML scalars. dev.env is the laptop file and
	# keeps its value on purpose (existing volumes already have it).
	if grep -rq --exclude=check-app-role-secret.sh --exclude=dev.env 'marula_app:marula_app' "$ROOT/deploy"; then
		bad "a deploy/ file embeds the published app-role password in a URL"
	else
		ok "no deploy/ file embeds the app-role password in a URL"
	fi
else
	skip "docker compose or python3 not available"
fi

printf '\n'
if [ "$FAIL" -ne 0 ]; then
	printf 'app-role credential checks FAILED (%d)\n' "$FAIL"
	exit 1
fi
printf 'app-role credential checks OK\n'
