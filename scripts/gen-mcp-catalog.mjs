#!/usr/bin/env node
// Derives the MCP read surface from ONE source: the OpenAPI snapshot plus the
// authored policy in mcp-catalog.config.json. Writes two artifacts, both of
// which consumers read instead of re-deriving:
//
//   packages/sdk/mcp-catalog.json                     — families, capabilities, tools
//   crates/core-db/migrations/0171_mcp_catalog_cutover.sql — revocation of grants
//                                                        outside the derived set
//
// The conformance test (crates/core-api/src/mcp_catalog.rs) asserts the
// catalog, the mintable :read scopes and the key allowance agree. Run
// scripts/check-mcp-catalog.sh to prove the checked-in artifacts are current.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const spec = JSON.parse(readFileSync(join(root, "packages/sdk/openapi.json"), "utf8"));
const config = JSON.parse(readFileSync(join(root, "packages/sdk/mcp-catalog.config.json"), "utf8"));

// The catalog's own inclusion floor: sensitive prefixes that never become
// tools regardless of policy (they are not org work reads at all).
const BASE_EXCLUDE_PREFIXES = [
  "/api/v1/attachments", "/api/v1/org/exports", "/api/v1/webhooks",
  "/api/v1/api-keys", "/api/v1/auth", "/api/v1/email", "/api/v1/internal",
  "/api/v1/portal",
];

const legacy = (p) => p.replace("/api/v1", "/api");
const familyOf = (p) => legacy(p).split("/")[2] ?? "root";

const sensitiveCapByPath = new Map();
for (const group of config.sensitive_tools) {
  for (const p of group.paths) {
    if (sensitiveCapByPath.has(p)) throw new Error(`path assigned twice: ${p}`);
    sensitiveCapByPath.set(p, group.capability);
  }
}

const families = new Map();
for (const [path, item] of Object.entries(spec.paths)) {
  const op = item.get;
  if (!op || !op.operationId) continue;
  if (BASE_EXCLUDE_PREFIXES.some((e) => path.startsWith(e))) continue;
  if (path.includes("/attachments")) continue;
  const path2 = legacy(path);
  const ns = familyOf(path);
  if (config.exclude_families.includes(ns)) continue;
  const excluded = config.exclude_paths[ns] ?? [];
  if (excluded.includes(path2)) continue;
  if (!families.has(ns)) families.set(ns, []);
  families.get(ns).push({
    name: op.operationId,
    path: path2,
    capability: sensitiveCapByPath.get(path2) ?? `${ns}:read`,
    summary: (op.summary ?? "").slice(0, 160),
  });
}

const out = {
  version: config.version,
  generated_from: "packages/sdk/openapi.json + packages/sdk/mcp-catalog.config.json",
  families: [...families.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([namespace, tools]) => ({
      namespace,
      capability: `${namespace}:read`,
      sensitive: config.sensitive_families.includes(namespace),
      tools: tools.sort((a, b) => a.path.localeCompare(b.path)),
    })),
  sensitive_capabilities: config.sensitive_tools.map((g) => ({
    capability: g.capability,
    namespace: familyOf(g.paths[0]),
    paths: g.paths,
  })),
};

// Capabilities an org may hold: every family read capability and every
// declared sensitive sub-capability. :write is absent — this release has no
// write tools, and the cutover revokes any :write grant along with the rest.
const grantable = new Set();
for (const f of out.families) grantable.add(f.capability);
for (const s of out.sensitive_capabilities) grantable.add(s.capability);

writeFileSync(join(root, "packages/sdk/mcp-catalog.json"), JSON.stringify(out, null, 2) + "\n");

const allowed = [...grantable].sort();
const quoted = allowed.map((c) => `'${c.replace(/'/g, "''")}'`).join(",\n  ");
const migration = `-- Generated by scripts/gen-mcp-catalog.mjs (row A29). Do not hand-edit:
-- change packages/sdk/mcp-catalog.config.json and re-run the generator.
--
-- Cuts the capability registry over to the derived catalog. No tenants were
-- running at cutover (user direction 2026-10-26), so grants outside the
-- derived set are revoked, not migrated: each revocation writes one audit
-- row with a system actor so the deletion is explainable.

WITH revoked AS (
  DELETE FROM mcp_capability_grants
  WHERE capability NOT IN (
  ${quoted}
  )
  RETURNING org_id, capability
)
INSERT INTO audit_events (id, org_id, actor_kind, actor_id, action, entity_type, entity_id, detail)
SELECT gen_random_uuid(), org_id, 'system', NULL, 'mcp_capability.revoked',
       'mcp_capability', capability,
       jsonb_build_object('reason', 'catalog cutover', 'row', 'A29')
FROM revoked;
`;
writeFileSync(join(root, "crates/core-db/migrations/0171_mcp_catalog_cutover.sql"), migration);

const totalTools = out.families.reduce((n, f) => n + f.tools.length, 0);
console.log(
  `mcp-catalog: ${out.families.length} families, ${totalTools} tools, ` +
    `${grantable.size} grantable capabilities`,
);
