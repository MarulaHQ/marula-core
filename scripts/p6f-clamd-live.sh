#!/usr/bin/env bash
# Live ClamAV leg for the scan gate (Wave 52 lane P6f).
#
# Purpose: put a REAL clamd in front of `ClamdScan` and the three gated doors,
# so the framing, the reply parsing and the fail-closed branches are measured
# against a daemon rather than against a fake socket that agrees with us.
#
# What it runs, in order:
#
#   1. boots `clamav/clamav` from a generated clamd.conf with a small
#      `StreamMaxLength`, so "a stream past the daemon's limit" is a cheap
#      case instead of a 26 MB one;
#   2. waits for the daemon to answer `zPING` (the signature DB has to be
#      loaded before it does);
#   3. `cargo test -p core-mail --test clamd_live -- --ignored --nocapture`
#      (the adapter against the daemon: clean, EICAR, the size-limit reply,
#      an empty stream, the version);
#   4. with `--doors`, `cargo test -p core-api --test clamd_doors_live --
#      --ignored --nocapture` (the ticket, document and vault doors through
#      the real router, with the scanner wired by `EMAIL_SCAN=clamd` +
#      `CLAMD_ADDR`, plus the stopped-daemon 503).
#
# Usage:
#
#   scripts/p6f-clamd-live.sh                 # daemon leg
#   scripts/p6f-clamd-live.sh --doors         # daemon + door legs
#   scripts/p6f-clamd-live.sh --keep          # leave the container running
#   scripts/p6f-clamd-live.sh down [RUN_ID]   # remove one run's container
#   scripts/p6f-clamd-live.sh down --doors    # also remove the pg harness
#
# Env knobs:
#   P6F_STREAM_MAX      clamd StreamMaxLength (default 1M)
#   CLAMAV_IMAGE        image (default clamav/clamav:stable)
#   P6F_PLATFORM        docker platform (default: linux/amd64 on arm64 hosts —
#                       the image publishes no arm64 manifest, so Docker
#                       Desktop runs it emulated; slower, still a real daemon)
#   P6F_RUN_ID          reuse a run id (container names are keyed by it)
#   P6F_TIMEOUT_SECS    how long to wait for the daemon (default 900)
#
# Every container is named `marula-clamd-<RUN_ID>`, so a parallel lane's daemon
# is never touched. `down` removes only the run it is given (or the last run
# recorded under $P6F_LOG_ROOT). Generated configs and the last-run pointer live
# outside the checkout, so a run leaves nothing in `git status`.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

IMAGE="${CLAMAV_IMAGE:-clamav/clamav:stable}"
STREAM_MAX="${P6F_STREAM_MAX:-1M}"
TIMEOUT_SECS="${P6F_TIMEOUT_SECS:-900}"
LOG_ROOT="${P6F_LOG_ROOT:-${TMPDIR:-/tmp}/marula-p6f}"
LAST_RUN_FILE="$LOG_ROOT/last-run"

say() { printf '\n== %s\n' "$*"; }
die() { printf 'p6f: %s\n' "$*" >&2; exit 1; }

docker_ok() { command -v docker >/dev/null 2>&1 && docker info >/dev/null 2>&1; }

# The official image is amd64-only (verified with `docker manifest inspect`:
# linux/amd64 and an attestation manifest, no arm64). On Apple Silicon the
# daemon then runs emulated, which is slow but real.
default_platform() {
  case "$(uname -m)" in
    arm64 | aarch64) printf 'linux/amd64' ;;
    *) printf '' ;;
  esac
}

run_id_from_args() {
  local candidate="${1:-}"
  if [[ -n "$candidate" && "$candidate" != -/* ]]; then
    printf '%s' "$candidate"
  elif [[ -f "$LAST_RUN_FILE" ]]; then
    cat "$LAST_RUN_FILE"
  else
    die "no run id given and none recorded"
  fi
}

down() {
  local with_doors=0 run
  for arg in "$@"; do
    case "$arg" in
      --doors) with_doors=1 ;;
      -*) die "unknown flag for down: $arg" ;;
      *) run="$arg" ;;
    esac
  done
  run="$(run_id_from_args "${run:-}")"
  local name="marula-clamd-$run"
  if docker ps -a --format '{{.Names}}' | grep -qx "$name"; then
    docker rm -f "$name" >/dev/null
    echo "removed $name"
  else
    echo "no container named $name"
  fi
  if (( with_doors )); then
    local pg="marula-p6f-clamd-pg18"
    if docker ps -a --format '{{.Names}}' | grep -qx "$pg"; then
      docker rm -f "$pg" >/dev/null
      echo "removed $pg"
    fi
  fi
}

conf_for() {
  local dir="$1"
  mkdir -p "$dir"
  cat >"$dir/clamd.conf" <<EOF
# Generated by scripts/p6f-clamd-live.sh. The small StreamMaxLength is what
# makes "an attachment bigger than the daemon will take" a cheap test case.
LocalSocket /tmp/clamd.sock
TCPSocket 3310
TCPAddr 0.0.0.0
StreamMaxLength $STREAM_MAX
MaxThreads 4
MaxConnectionQueueLength 8
DatabaseDirectory /var/lib/clamav
EOF
  printf '%s' "$dir/clamd.conf"
}

# zPING is the readiness probe: clamd only listens once it has the signature
# DB, so PONG means "scannable", not merely "container started".
wait_for_daemon() {
  local port="$1" deadline=$(( $(date +%s) + TIMEOUT_SECS ))
  while (( $(date +%s) < deadline )); do
    if python3 - "$port" <<'PY' 2>/dev/null
import socket, sys
port = int(sys.argv[1])
s = socket.create_connection(("127.0.0.1", port), timeout=2)
s.sendall(b"zPING\0")
reply = s.recv(64)
sys.exit(0 if reply.startswith(b"PONG") else 1)
PY
    then
      return 0
    fi
    sleep 2
  done
  return 1
}

stream_limit_bytes() {
  local raw="$STREAM_MAX"
  local num="${raw%[KkMmGg]}"
  local unit="${raw:${#num}:1}"
  num="${num%%.*}"
  case "$unit" in
    [Kk]) echo $(( num * 1024 )) ;;
    [Mm]) echo $(( num * 1024 * 1024 )) ;;
    [Gg]) echo $(( num * 1024 * 1024 * 1024 )) ;;
    *) echo "$num" ;;
  esac
}

up() {
  local with_doors=0
  for arg in "$@"; do
    case "$arg" in
      --doors) with_doors=1 ;;
      --keep) P6F_KEEP=1 ;;
      -*) die "unknown flag: $arg" ;;
    esac
  done
  docker_ok || die "docker is not running; this leg needs a real daemon"

  # The EXIT trap outlives this function, so the names it needs live at script
  # scope: a `local` here is unbound by the time teardown runs.
  local run="${P6F_RUN_ID:-p6f-$(date +%Y%m%d-%H%M%S)-$RANDOM}"
  local name="marula-clamd-$run"
  P6F_RUN="$run"
  P6F_CONTAINER_NAME="$name"
  local log_dir="$LOG_ROOT/$run"
  local conf
  conf="$(conf_for "$log_dir")"
  mkdir -p "$LOG_ROOT"
  printf '%s' "$run" >"$LAST_RUN_FILE"

  if docker ps -a --format '{{.Names}}' | grep -qx "$name"; then
    die "container $name already exists; run 'scripts/p6f-clamd-live.sh down $run' first"
  fi

  local platform
  platform="${P6F_PLATFORM:-$(default_platform)}"

  say "booting $IMAGE (run $run, StreamMaxLength $STREAM_MAX)"
  # Random host port: two lanes can run this at once, and no fixed 3310 is
  # assumed by anything here.
  local -a docker_args=(
    run -d --name "$name" --rm
    -p 127.0.0.1::3310
    -v "$conf:/etc/clamav/clamd.conf:ro"
  )
  if [[ -n "$platform" ]]; then
    docker_args+=(--platform "$platform")
    echo "platform: $platform (the image publishes no arm64 manifest, so this runs emulated)"
  fi
  docker "${docker_args[@]}" "$IMAGE" >/dev/null

  cleanup() {
    if [[ "${P6F_KEEP:-0}" == 1 ]]; then
      echo "kept container $P6F_CONTAINER_NAME (port mapping: $(docker port "$P6F_CONTAINER_NAME" 3310 2>/dev/null | head -1))"
      echo "remove it with: scripts/p6f-clamd-live.sh down $P6F_RUN"
    else
      docker rm -f "$P6F_CONTAINER_NAME" >/dev/null 2>&1 || true
    fi
  }
  trap cleanup EXIT

  if ! docker ps --format '{{.Names}}' | grep -qx "$name"; then
    echo "--- container exited; its log follows ---"
    docker logs "$name" 2>&1 | tail -30 || true
    die "clamd did not stay up (image: $IMAGE, platform: ${platform:-native})"
  fi

  local mapping port
  mapping="$(docker port "$name" 3310 | head -1)"
  port="${mapping##*:}"
  [[ -n "$port" ]] || die "could not read the mapped port from '$mapping'"
  echo "waiting for the signature DB and zPING on 127.0.0.1:$port (up to ${TIMEOUT_SECS}s)"
  if ! wait_for_daemon "$port"; then
    echo "--- container log ---"
    docker logs "$name" 2>&1 | tail -40 || true
    die "clamd never answered zPING within ${TIMEOUT_SECS}s (signature DB download?)"
  fi

  local stream_bytes
  stream_bytes="$(stream_limit_bytes)"
  export CLAMD_LIVE_ADDR="127.0.0.1:$port"
  # The door leg builds its scanner through Config::from_env, which is the
  # production path this lane exists to prove.
  export CLAMD_ADDR="$CLAMD_LIVE_ADDR"
  export EMAIL_SCAN=clamd
  export CLAMD_LIVE_STREAM_MAX_BYTES="$stream_bytes"

  say "daemon is answering; adapter leg"
  cargo test -p core-mail --test clamd_live -- --ignored --nocapture --test-threads=1

  if (( with_doors )); then
    say "door leg (ticket, document, vault, stopped daemon)"
    echo "note: this leg needs a database. It reuses MARULA_TEST_DATABASE_URL/DATABASE_URL when set,"
    echo "      otherwise it boots the reusable pgvector harness container marula-p6f-clamd-pg18."
    cargo test -p core-api --test clamd_doors_live -- --ignored --nocapture --test-threads=1
  fi

  say "live leg complete (run $P6F_RUN)"
}

case "${1:-}" in
  down) shift; down "$@" ;;
  "") up ;;
  --*) up "$@" ;;
  -h | --help)
    sed -n '2,50p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    ;;
  *) die "unknown command: $1 (try --help)" ;;
esac
