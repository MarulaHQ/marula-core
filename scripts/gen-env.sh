#!/usr/bin/env bash
# gen-env.sh — write the env file the compose stack needs, with real secrets.
#
# The installer generates these itself. This script is for the compose path:
# someone who would rather run `docker compose up -d` than a wizard, and who
# should not be pasting a published development secret into a server.
#
#   scripts/gen-env.sh                     # writes ./marula.env
#   scripts/gen-env.sh /srv/marula/marula.env
#   scripts/gen-env.sh --force marula.env  # replace one that is already there
#
# The eight values and why each exists are documented in `deploy/env.example`;
# this script writes the same names with 32 random bytes each, in the same shape
# `marula install` writes, so either file can be handed to the same compose
# command.
#
# Non-purpose: it does not start anything, and it does not rotate an existing
# file. Replacing a live env file rotates the signing key (signing everyone out)
# and the database password the volume was initialised with, which is why
# overwriting needs --force.
set -euo pipefail

say() { printf '==> %s\n' "$*"; }
die() { printf 'gen-env: %s\n' "$*" >&2; exit 1; }

FORCE=0
OUT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --force) FORCE=1; shift ;;
    -h | --help)
      awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"
      exit 0
      ;;
    -*)
      die "unknown flag $1"
      ;;
    *)
      [ -z "$OUT" ] || die "one output path, not two"
      OUT="$1"
      shift
      ;;
  esac
done
OUT="${OUT:-marula.env}"

command -v openssl >/dev/null 2>&1 || die "openssl is not on PATH; it is how the secrets are made"

if [ -e "$OUT" ] && [ "$FORCE" -eq 0 ]; then
  die "$OUT already exists. Replacing it rotates the signing key and the database password. Pass --force only if you mean that."
fi

secret() {
  local value
  value=$(openssl rand -hex 32) || die "openssl failed; refusing to write an empty secret"
  [ ${#value} -eq 64 ] || die "openssl returned ${#value} characters, not 64; refusing to write it"
  printf '%s' "$value"
}

# Generate first, write second: a command substitution inside a heredoc does not
# stop the script when it fails, and a file with `JWT_SECRET=` in it is worse
# than no file at all.
JWT_SECRET=$(secret)
MARULA_SECRET_KEY=$(secret)
MARULA_INTERNAL_TOKEN=$(secret)
EMAIL_INTERNAL_TOKEN=$(secret)
POSTGRES_PASSWORD=$(secret)
MARULA_APP_PASSWORD=$(secret)
GARAGE_RPC_SECRET=$(secret)
GLITCHTIP_SECRET_KEY=$(secret)

# A temp file in the destination directory, so `mv` is a rename and never a
# copy across filesystems. umask 077 also covers the case where an old file at
# $OUT had a wider mode.
TMP=$(mktemp "$OUT.XXXXXX")
trap 'rm -f "$TMP"' EXIT

say "writing $OUT"
cat >"$TMP" <<EOF
# Generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ).
# Every value is a secret. Do not commit this file.

# Signs every session token. Rotating it signs everyone out.
JWT_SECRET=$(secret)

# Encrypts stored connector credentials and webhook signing keys. Rotating it
# makes those values unreadable, so back it up with the database.
MARULA_SECRET_KEY=$(secret)

# Authenticates service-to-service calls inside the stack.
MARULA_INTERNAL_TOKEN=$(secret)

# Authenticates the mail path between core-api and the email service.
EMAIL_INTERNAL_TOKEN=$(secret)

# The Postgres owner role. Applied by initdb on the first boot only.
POSTGRES_PASSWORD=$(secret)

# The application role, subject to row-level security.
MARULA_APP_PASSWORD=$(secret)

# The object store's inter-node secret.
GARAGE_RPC_SECRET=$(secret)

# The error tracker's own encryption key.
GLITCHTIP_SECRET_KEY=$(secret)
EOF
chmod 600 "$TMP"
mv -f "$TMP" "$OUT"
trap - EXIT

say "wrote $OUT with eight secrets (mode 600)"
printf 'next: docker compose --env-file %s -f deploy/docker-compose.yml up -d\n' "$OUT"
