import { chromium } from "playwright";
const BASE="http://127.0.0.1:15435"; const API="http://127.0.0.1:15433";
const b=await chromium.launch({ args: ["--no-proxy-server"] });
const ctx=await b.newContext({ viewport: { width: 1440, height: 900 } });
const p=await ctx.newPage();
await p.addInitScript(([apiBase,mode,preset])=>{
  window.__MERIDIAN_API_URL__=apiBase;
  localStorage.setItem("meridian-theme",mode);
  localStorage.setItem("meridian-theme-preset",preset);
},[API,"dark","tangerine"]);
p.on("response", r=>{ if(r.url().includes(API)&&!r.url().includes("oidc")) console.log("API",r.status(),r.url().slice(0,70)); });
p.on("requestfailed", r=>console.log("FAILED",r.method(),r.url()));
p.on("console", m=>{ if(m.type()==="error") console.log("CONSOLE", m.text().slice(0,200)); });
p.on("pageerror", e=>console.log("PAGEERR", String(e).slice(0,300)));
await p.goto(`${BASE}/login`,{waitUntil:"networkidle"});
await p.locator('input[type="email"], input[name*="email" i]').first().fill("owner@demo.local");
await p.locator('input[type="password"]').first().fill("demo-password-123");
await p.getByRole("button",{name:/sign in/i}).click();
await p.waitForTimeout(6000);
console.log("after login:", p.url());
await p.goto(`${BASE}/settings/appearance`,{waitUntil:"networkidle"});
await p.waitForTimeout(2000);
console.log("final:", p.url());
await b.close();
