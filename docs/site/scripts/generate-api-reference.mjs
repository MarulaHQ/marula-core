#!/usr/bin/env node
// Generates docs/site/reference/api.md from the committed OpenAPI pin.
// Reads ONLY the compact single-line pin (packages/sdk/openapi.json) — the
// pretty form is never read or emitted (DX12). Deterministic output.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const pinPath = join(root, "packages/sdk/openapi.json");
const outPath = join(root, "docs/site/reference/api.md");

const raw = readFileSync(pinPath, "utf8");
if (raw.includes("\n") && raw.trim().split("\n").length > 1) {
  throw new Error("OpenAPI pin is not compact single-line (DX12) — regenerate with `pnpm --filter @marula-core/sdk generate` first.");
}
const spec = JSON.parse(raw);
if (spec.openapi?.startsWith("3.") === false) throw new Error("unexpected OpenAPI version: " + spec.openapi);

const schemaName = ($ref) => ($ref || "").split("/").pop() || "";
const schemaLabel = (s) => {
  if (!s) return "—";
  if (s.$ref) return `[${schemaName(s.$ref)}](#schema-${schemaName(s.$ref).toLowerCase()})`;
  if (s.allOf?.length && s.allOf[0].$ref) {
    const base = schemaName(s.allOf[0].$ref);
    return `[${base}](#schema-${base.toLowerCase()}) + extension${s.allOf.length > 2 ? "s" : ""}`;
  }
  if (Array.isArray(s.type)) return s.type.filter((t) => t !== "null").join(" | ");
  return s.type || "object";
};

const groups = new Map();
for (const [path, item] of Object.entries(spec.paths)) {
  const seg = path.split("/")[3] || path.split("/")[2] || "root";
  if (!groups.has(seg)) groups.set(seg, []);
  for (const method of ["get", "post", "patch", "put", "delete"]) {
    const op = item[method];
    if (!op) continue;
    groups.get(seg).push({ method: method.toUpperCase(), path, op });
  }
}
for (const ops of groups.values()) ops.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

const lines = [];
lines.push(`---`);
lines.push(`description: "Marula Core API reference: endpoints, operations, request bodies and schemas from the committed OpenAPI pin."`);
lines.push(`---`);
lines.push("");
lines.push(`<!-- GENERATED by docs/site/scripts/generate-api-reference.mjs from packages/sdk/openapi.json — do not edit by hand. -->`);
lines.push(`# API reference`);
lines.push("");
lines.push(`**Marula Core API ${spec.info.version}** — ${spec.info.description} Generated from the committed [OpenAPI pin](openapi.md) (\`packages/sdk/openapi.json\`), which is byte-identical to \`fixtures/openapi/v1/openapi.json\`. License: ${spec.info.license?.name ?? "—"}.`);
lines.push("");
lines.push(`**${spec.paths ? Object.keys(spec.paths).length : 0} paths · ${[...groups.values()].reduce((n, ops) => n + ops.length, 0)} operations · ${Object.keys(spec.components?.schemas ?? {}).length} schemas.**`);
lines.push("");
for (const [seg, ops] of [...groups.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(`## ${seg}`);
  lines.push("");
  lines.push("| Method | Path | Operation | Request body |");
  lines.push("|---|---|---|---|");
  for (const { method, path, op } of ops) {
    const body = op.requestBody?.content?.["application/json"]?.schema;
    const anchor = op.operationId ? ` <a id="${op.operationId}"></a>` : "";
    const summary = (op.summary || op.operationId || "—").replace(/\s+/g, " ").trim();
    lines.push(`| \`${method}\` | \`${path}\`${anchor} | ${summary} | ${schemaLabel(body)} |`);
  }
  lines.push("");
}
lines.push(`## Schemas`);
lines.push("");
const schemas = Object.entries(spec.components?.schemas ?? {}).sort((a, b) => a[0].localeCompare(b[0]));
lines.push("| Schema | Type | Description |");
lines.push("|---|---|---|");
for (const [name, s] of schemas) {
  const type = Array.isArray(s.type) ? s.type.filter((t) => t !== "null").join(" | ") : s.type || (s.allOf ? "composite" : "object");
  const desc = (s.description || "").replace(/\|/g, "\\|").replace(/\s+/g, " ").slice(0, 200);
  lines.push(`| <a id="schema-${name.toLowerCase()}"></a>\`${name}\` | ${type} | ${desc} |`);
}
lines.push("");
lines.push(`*Tagged ${spec.tags?.length ?? 0} operation groups; schema count ${schemas.length} matches the pin. Regenerate with \`node docs/site/scripts/generate-api-reference.mjs\` after any OpenAPI regen.*`);

writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`wrote ${outPath}: ${Object.keys(spec.paths).length} paths, ${schemas.length} schemas`);
