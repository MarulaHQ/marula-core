#!/usr/bin/env node
// Renders docs/site/reference/upgrade-matrix.md from fixtures/upgrades/.
// Deterministic: reads fixture files present on disk, emits the N−2 matrix.
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const fixturesDir = join(root, "fixtures/upgrades");
const outPath = join(root, "docs/site/reference/upgrade-matrix.md");

const versions = readdirSync(fixturesDir)
  .filter((n) => /^v\d+\.\d+\.\d+$/.test(n))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

const rows = [];
for (const v of versions) {
  const manifestPath = join(fixturesDir, `${v}.manifest.json`);
  const seedPath = join(fixturesDir, `${v}.seed.sql.gz`);
  const seedDir = join(fixturesDir, v, "seed_org.sql");
  if (!existsSync(manifestPath) || !existsSync(seedPath)) continue;
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const sections = Object.entries(manifest.sections ?? {})
    .map(([k, v]) => `${k} (${Array.isArray(v) ? v.length : 1})`)
    .join(", ");
  rows.push({
    version: v,
    org_id: manifest.org_id,
    generated_at: manifest.generated_at,
    surfaces: sections || "—",
    seed_gz: existsSync(seedPath),
    seed_source: existsSync(seedDir),
  });
}

const latest = rows[rows.length - 1];

const lines = [];
lines.push(`<!-- GENERATED by docs/site/scripts/generate-upgrade-matrix.mjs from fixtures/upgrades/ — do not edit by hand. -->`);
lines.push(`# Upgrade matrix`);
lines.push("");
lines.push(`Every tagged release ships with a CI-proven upgrade path from each of the two previous tagged releases (the **N−2 rule**, [policy](../../upgrade-compatibility-policy.md) §1/§8). CI restores each fixture snapshot (a production-like seeded org exercising every customization surface), migrates to HEAD, and runs the API/event conformance suites.`);
lines.push("");
lines.push(`**Latest fixture anchor: \`${latest?.version ?? "none"}\`.** Capture happens at tag time — old snapshots cannot be reconstructed (see [fixtures/upgrades/README.md](../../../fixtures/upgrades/README.md)).`);
lines.push("");
lines.push(`| Fixture | Org anchor | Captured | Seed dump | Seed source | Customization surfaces covered (count) |`);
lines.push(`|---|---|---|---|---|---|`);
for (const r of rows) {
  lines.push(`| \`${r.version}\` | \`${r.org_id}\` | ${r.generated_at?.slice(0, 10) ?? "—"} | ${r.seed_gz ? "✓ `v" + r.version.slice(1) + ".seed.sql.gz`" : "missing"} | ${r.seed_source ? "✓" : "—"} | ${r.surfaces} |`);
}
lines.push("");
lines.push(`## Notes`);
lines.push("");
lines.push(`- The N−2 matrix anchors on ${rows[0]?.version ?? "—"} onward; earlier captures were scoped out of their wave (fixtures README).`);
lines.push(`- Jump distance at upgrade time: up to two releases behind; further jumps apply the same machinery sequentially.`);
lines.push(`- Run the preflight before upgrading: \`marula upgrade --check\` — see the [upgrade how-to](../how-to/upgrade.md).`);
lines.push(`- CI cross-checks customization tables against anything a migration modifies; customizations are migrated as data ([explanation](../explanation/customizations-are-data.md)).`);

writeFileSync(outPath, lines.join("\n") + "\n");
console.log(`wrote ${outPath}: ${rows.length} fixture(s), latest ${latest?.version}`);
