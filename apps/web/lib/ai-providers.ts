// Shared AI provider metadata — the ONE list both onboarding's AI setup step
// (components/onboarding/ai-setup-step.tsx) and the settings BYOK card
// (components/settings/byok-legacy-card.tsx) read, so the provider ids,
// names and the "what it needs" line can never drift between the wizard and
// Settings.
//
// The wire ids are the backend's closed vocabulary
// (crates/core-domain/src/settings.rs AI_PROVIDER_OPTIONS): the BYOK seal
// surface accepts exactly these for AI providers. `gemini` and `openrouter`
// are NOT in it — they render as visible-but-disabled choices with an honest
// note until the backend grows a slot for them (flagged as a backend gap in
// the W72 lane report, never invented client-side).

export type AiProviderNeed = "api_key" | "none" | "api_key_remote_base_url";

export interface AiProviderMeta {
  /** The wire provider id the seal/test surfaces accept. */
  id: string;
  /** Display name — the product name, with the company where it helps. */
  name: string;
  /** Neutral monogram (1–2 letters). No fake logos, by design. */
  monogram: string;
  /** What the operator needs to have at hand, in one line. */
  need: AiProviderNeed;
  /** One line on what this provider is for, in the step's voice. */
  blurb: string;
  /** False while the backend's seal surface refuses this id. */
  backed: boolean;
}

